FIRST = 0x20
LAST = 0x7E


def encode(glyph_art):
    rows = glyph_art.split("/")
    if len(rows) != 7 or any(len(r) != 5 for r in rows):
        raise ValueError("字形必须是 7 行 x 5 列: %r" % glyph_art)
    cols = []
    for c in range(5):
        b = 0
        for r in range(7):
            if rows[r][c] == "#":
                b |= (1 << r)
        cols.append(b)
    return cols


def c_escape(ch):
    if ch == "\\":
        return "'\\\\'"
    if ch == "'":
        return "'\\''"
    return "'%s'" % ch


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    out_c = os.path.join(root, "firmware", "drivers", "oled_font.c")

    if len(GLYPHS) != (LAST - FIRST + 1):
        print("字形数量错误：%d，应为 %d" % (len(GLYPHS), LAST - FIRST + 1))
        return 1

    lines = []
    lines.append("/*")
    lines.append(" * oled_font.c -- 5x7 ASCII 点阵字库（自建，由 tools/gen_oled_font.py 生成）")
    lines.append(" *")
    lines.append(" * 覆盖可打印 ASCII 0x%02X..0x%02X。每字符 5 列，每列 1 字节：" % (FIRST, LAST))
    lines.append(" * bit0 = 顶行 ... bit6 = 底行，bit7 恒为 0。")
    lines.append(" * 生成命令：python tools/gen_oled_font.py")
    lines.append(" */")
    lines.append('#include "oled_font.h"')
    lines.append("")
    lines.append("const uint8_t oled_font5x7[][OLED_FONT_WIDTH] = {")
    for i, (ch, art) in enumerate(GLYPHS):
        cols = encode(art)
        hexs = ", ".join("0x%02X" % c for c in cols)
        lines.append("    { %s },  /* 0x%02X %s */" % (hexs, FIRST + i, c_escape(ch)))
    lines.append("};")
    lines.append("")
    lines.append("const uint8_t *oled_font_glyph(char c)")
    lines.append("{")
    lines.append("    unsigned idx;")
    lines.append("")
    lines.append("    idx = (unsigned)(unsigned char)c;")
    lines.append("    if ((idx < OLED_FONT_FIRST_CHAR) || (idx > OLED_FONT_LAST_CHAR)) {")
    lines.append("        idx = (unsigned)'?';   /* 不可打印字符统一显示为 '?'，便于排错 */")
    lines.append("    }")
    lines.append("    return oled_font5x7[idx - OLED_FONT_FIRST_CHAR];")
    lines.append("}")
    lines.append("")

    with open(out_c, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("生成 %s（%d 个字形）" % (out_c, len(GLYPHS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
